import type { ApiIR } from "../ir/api.ts";
import type { ServiceIR, ServiceMethodIR, HttpServiceMethodIR } from "../ir/service.ts";
import { isHttpMethod } from "../ir/service.ts";
import type { TypeIR } from "../ir/types.ts";
import type { Generator, GeneratorContext, GeneratedFiles } from "./generator.ts";
import { tsClientGenerator, methodNames, type TsClientOptions } from "./tsClient.ts";
import { docComment } from "./tsTypes.ts";

export interface ReactQueryOptions extends TsClientOptions {}

interface QueryOp {
  name: string;
  capitalName: string;
  pathTemplate: string;
  hasSlots: boolean;
  hasRequiredSlots: boolean;
  doc?: string;
}

interface MutationOp {
  name: string;
  capitalName: string;
  pathTemplate: string;
  method: string;
  hasSlots: boolean;
  doc?: string;
}

function methodDoc(method: ServiceMethodIR): string {
  const isHttp = isHttpMethod(method);
  const summary = isHttp ? method.summary : undefined;
  const description = isHttp ? method.description : undefined;
  const deprecated = isHttp && method.deprecated ? { isDeprecated: true } : undefined;
  return docComment(
    {
      description: [summary, description]
        .filter((line): line is string => Boolean(line))
        .join("\n\n") || undefined,
      deprecated,
    },
    ""
  );
}

function emitReactQueryFiles(
  service: ServiceIR,
  context: GeneratorContext<ReactQueryOptions>
): GeneratedFiles {
  const names = methodNames(service);
  const queryOps: QueryOp[] = [];
  const mutationOps: MutationOp[] = [];

  for (const method of service.methods) {
    const name = names.get(method)!;
    const capitalName = name.charAt(0).toUpperCase() + name.slice(1);
    const doc = methodDoc(method);

    const isHttp = isHttpMethod(method);
    const httpMethod = isHttp ? method.address.method.toUpperCase() : "POST";
    const pathTemplate = isHttp
      ? method.address.path
      : (method.address as any).service
        ? `${(method.address as any).service}/${(method.address as any).method}`
        : "call";

    const isQuery = isHttp && ["GET", "HEAD", "OPTIONS"].includes(httpMethod);

    let hasSlots = false;
    let hasRequiredSlots = false;

    if (isHttp) {
      const http = method as HttpServiceMethodIR;
      const params = http.request.parameters ?? [];
      const hasBody = Boolean(http.request.body && http.request.body.length > 0);
      hasSlots = params.length > 0 || hasBody;

      const hasPath = params.some((p) => p.in === "path");
      const hasReqParam = params.some((p) => p.required);
      const hasReqBody = hasBody && http.request.bodyRequired !== false;

      hasRequiredSlots = hasPath || hasReqParam || hasReqBody;
    } else {
      hasSlots = true;
      hasRequiredSlots = true;
    }

    if (isQuery) {
      queryOps.push({
        name,
        capitalName,
        pathTemplate,
        hasSlots,
        hasRequiredSlots,
        doc,
      });
    } else {
      mutationOps.push({
        name,
        capitalName,
        pathTemplate,
        method: httpMethod,
        hasSlots,
        doc,
      });
    }
  }

  const banner = (what: string) =>
    `// Generated by wiz from ${service.name ?? "an OpenAPI document"}.\n` +
    `// ${what} Edit the document, not this file.\n`;

  const queryCode = [
    banner("React Query options getters and hooks for query operations."),
    'import { useQuery, type UseQueryOptions } from "@tanstack/react-query";',
    'import { createClient, type Client } from "./api.ts";',
    'import { createMutations } from "./mutations.ts";',
    "",
    ...queryOps.flatMap((op) => {
      const pathLit = JSON.stringify(op.pathTemplate);
      const optParamDecl = op.hasRequiredSlots
        ? `options: Parameters<Client["${op.name}"]>[0]`
        : `options?: Parameters<Client["${op.name}"]>[0]`;
      const callArgs = op.hasSlots
        ? `options as any, { signal }`
        : `{ ...options, signal } as any`;

      const optionsFnDoc = op.doc
        ? op.doc
        : `/** Query options getter for \`${op.name}\`. */\n`;
      const hookDoc = `/** React Query hook for \`${op.name}\`. */\n`;

      return [
        `${optionsFnDoc}export function get${op.capitalName}QueryOptions<`,
        `  TData = Awaited<ReturnType<Client["${op.name}"]>>,`,
        "  TError = unknown",
        ">(",
        `  ${optParamDecl},`,
        `  queryOptions?: Omit<UseQueryOptions<Awaited<ReturnType<Client["${op.name}"]>>, TError, TData>, "queryKey" | "queryFn">,`,
        "  client: Client = createClient()",
        ") {",
        "  return {",
        `    queryKey: [${pathLit}, options] as const,`,
        "    queryFn: ({ signal }: { signal?: AbortSignal }) =>",
        `      client.${op.name}(${callArgs}),`,
        "    ...queryOptions,",
        "  };",
        "}",
        "",
        `${hookDoc}export function use${op.capitalName}<`,
        `  TData = Awaited<ReturnType<Client["${op.name}"]>>,`,
        "  TError = unknown",
        ">(",
        `  ${optParamDecl},`,
        `  queryOptions?: Omit<UseQueryOptions<Awaited<ReturnType<Client["${op.name}"]>>, TError, TData>, "queryKey" | "queryFn">,`,
        "  client: Client = createClient()",
        ") {",
        `  return useQuery(get${op.capitalName}QueryOptions(options${op.hasRequiredSlots ? "" : "!"}, queryOptions, client));`,
        "}",
        "",
      ];
    }),
    "/** Factory binding all query options getters and query hooks to a custom client instance. */",
    "export function createQueries(client: Client = createClient()) {",
    "  return {",
    ...queryOps.map((op) => {
      const optParamDecl = op.hasRequiredSlots
        ? `options: Parameters<Client["${op.name}"]>[0]`
        : `options?: Parameters<Client["${op.name}"]>[0]`;
      return [
        `    get${op.capitalName}QueryOptions: <TData = Awaited<ReturnType<Client["${op.name}"]>>, TError = unknown>(`,
        `      ${optParamDecl},`,
        `      queryOptions?: Omit<UseQueryOptions<Awaited<ReturnType<Client["${op.name}"]>>, TError, TData>, "queryKey" | "queryFn">`,
        `    ) => get${op.capitalName}QueryOptions<TData, TError>(options${op.hasRequiredSlots ? "" : "!"}, queryOptions, client),`,
        `    use${op.capitalName}: <TData = Awaited<ReturnType<Client["${op.name}"]>>, TError = unknown>(`,
        `      ${optParamDecl},`,
        `      queryOptions?: Omit<UseQueryOptions<Awaited<ReturnType<Client["${op.name}"]>>, TError, TData>, "queryKey" | "queryFn">`,
        `    ) => use${op.capitalName}<TData, TError>(options${op.hasRequiredSlots ? "" : "!"}, queryOptions, client),`,
      ].join("\n");
    }),
    "  };",
    "}",
    "",
    "/** Factory binding all query and mutation hooks to a custom client instance. */",
    "export function createHooks(client: Client = createClient()) {",
    "  return {",
    "    ...createQueries(client),",
    "    ...createMutations(client),",
    "  };",
    "}",
    "",
  ].join("\n");

  const mutationCode = [
    banner("React Query options getters and hooks for mutation operations."),
    'import { useMutation, type UseMutationOptions } from "@tanstack/react-query";',
    'import { createClient, type Client } from "./api.ts";',
    "",
    ...mutationOps.flatMap((op) => {
      const pathLit = JSON.stringify(op.pathTemplate);
      const methodLit = JSON.stringify(op.method);
      const optionsFnDoc = op.doc
        ? op.doc
        : `/** Mutation options getter for \`${op.name}\`. */\n`;
      const hookDoc = `/** React Query hook for \`${op.name}\`. */\n`;

      return [
        `${optionsFnDoc}export function get${op.capitalName}MutationOptions<`,
        `  TData = Awaited<ReturnType<Client["${op.name}"]>>,`,
        "  TError = unknown",
        ">(",
        `  mutationOptions?: Omit<UseMutationOptions<TData, TError, Parameters<Client["${op.name}"]>[0]>, "mutationFn">,`,
        "  client: Client = createClient()",
        ") {",
        "  return {",
        `    mutationKey: [${pathLit}, ${methodLit}] as const,`,
        `    mutationFn: (options: Parameters<Client["${op.name}"]>[0]) =>`,
        `      client.${op.name}(options as any),`,
        "    ...mutationOptions,",
        "  };",
        "}",
        "",
        `${hookDoc}export function use${op.capitalName}<`,
        `  TData = Awaited<ReturnType<Client["${op.name}"]>>,`,
        "  TError = unknown",
        ">(",
        `  mutationOptions?: Omit<UseMutationOptions<TData, TError, Parameters<Client["${op.name}"]>[0]>, "mutationFn">,`,
        "  client: Client = createClient()",
        ") {",
        `  return useMutation(get${op.capitalName}MutationOptions(mutationOptions, client));`,
        "}",
        "",
      ];
    }),
    "/** Factory binding all mutation options getters and mutation hooks to a custom client instance. */",
    "export function createMutations(client: Client = createClient()) {",
    "  return {",
    ...mutationOps.map((op) => {
      return [
        `    get${op.capitalName}MutationOptions: <TData = Awaited<ReturnType<Client["${op.name}"]>>, TError = unknown>(`,
        `      mutationOptions?: Omit<UseMutationOptions<TData, TError, Parameters<Client["${op.name}"]>[0]>, "mutationFn">`,
        `    ) => get${op.capitalName}MutationOptions<TData, TError>(mutationOptions, client),`,
        `    use${op.capitalName}: <TData = Awaited<ReturnType<Client["${op.name}"]>>, TError = unknown>(`,
        `      mutationOptions?: Omit<UseMutationOptions<TData, TError, Parameters<Client["${op.name}"]>[0]>, "mutationFn">`,
        `    ) => use${op.capitalName}<TData, TError>(mutationOptions, client),`,
      ].join("\n");
    }),
    "  };",
    "}",
    "",
  ].join("\n");

  return {
    "queries.ts": queryCode,
    "mutations.ts": mutationCode,
  };
}

export const reactQueryGenerator: Generator<ReactQueryOptions> = {
  name: "react-query-client",

  api(ir: ApiIR, context) {
    const baseFiles = tsClientGenerator.api!(ir, context);
    const reactQueryFiles = emitReactQueryFiles(ir.service, context);
    return { ...baseFiles, ...reactQueryFiles };
  },

  service(ir: ServiceIR, context) {
    const baseFiles = tsClientGenerator.service!(ir, context);
    const reactQueryFiles = emitReactQueryFiles(ir, context);
    return { ...baseFiles, ...reactQueryFiles };
  },

  type(ir: TypeIR, context) {
    return tsClientGenerator.type ? tsClientGenerator.type(ir, context) : {};
  },
};

export default reactQueryGenerator;
